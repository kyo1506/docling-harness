import json
import pathlib
from .models import HarnessOutput, CostComparison


def write_output(output: HarnessOutput, comparison: CostComparison, output_dir: str, source_count: int):
    out = pathlib.Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    output.meta["sources_processed"] = source_count
    output.meta["cost_comparison"] = {
        "raw_tokens": comparison.raw_tokens,
        "processed_tokens": comparison.processed_tokens,
        "reduction_pct": comparison.reduction_pct,
        "break_even_queries": comparison.break_even_queries,
    }

    data = {
        "_meta": output.meta,
        "specs": output.specs,
        "loop_engineering": output.loop_engineering,
        "harness_engineering": output.harness_engineering,
    }

    json_path = out / "harness.json"
    json_path.write_text(json.dumps(data, indent=2, ensure_ascii=False))

    agents_md = _build_agents_md(data)
    (out / "AGENTS.md").write_text(agents_md)


def _build_agents_md(data: dict) -> str:
    specs = data.get("specs", {})
    loop = data.get("loop_engineering", {})
    harness = data.get("harness_engineering", {})

    specs_summary = specs.get("summary", "")
    reqs = specs.get("requirements", [])
    models = specs.get("data_models", [])
    rules = specs.get("business_rules", [])
    acs = specs.get("acceptance_criteria", [])

    loop_summary = loop.get("summary", "")
    triggers = loop.get("automation_triggers", [])
    points = loop.get("verification_points", [])
    feedback = loop.get("feedback_loops", [])

    harness_summary = harness.get("summary", "")
    ctx_rules = harness.get("context_rules", [])
    gates = harness.get("validation_gates", [])
    tools = harness.get("tool_requirements", [])

    return f"""# Context (generated by docling-harness)

## Specs
{specs_summary}

- {len(reqs)} requirements → [harness.json](harness.json)
- {len(acs)} acceptance criteria
- {len(models)} data models
- {len(rules)} business rules

## Loop Engineering
{loop_summary}

- {len(triggers)} automation triggers → [harness.json](harness.json)
- {len(points)} verification points
- {len(feedback)} feedback loops

## Harness Engineering
{harness_summary}

- {len(ctx_rules)} context rules → [harness.json](harness.json)
- {len(gates)} validation gates
- {len(tools)} tool requirements
"""
